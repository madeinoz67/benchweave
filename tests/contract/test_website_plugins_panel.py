def test_hand_edited_panel_row_refuses(tmp_path: Path) -> None:
    """B2 plant 3: a hand-edited panel row is refused by the tool's --check
    with its machine prefix — the guard, not a sweep."""
    root = _sandbox(tmp_path)
    index = root / "website" / "index.html"
    html = index.read_text(encoding="utf-8")
    planted = html.replace("data-bw-slot=\"summary\">", "data-bw-slot=\"summary\">hand-edited ", 1)
    assert planted != html
    index.write_text(planted, encoding="utf-8")
    result = _run_tool("--check", root=root)
    assert result.returncode == 1, result.stdout + result.stderr
    assert "panel_drift:" in result.stderr


def test_hand_edited_mirror_row_refuses(tmp_path: Path) -> None:
    """B2 plant 2, render half: a hand-edited mirror row that changes rendered
    content reddens --check (the committed block no longer matches a fresh
    render of the planted mirror). The authority pin catches non-rendering
    edits — that is the other half, scripts/website/check_mirror_authority.py."""
    root = _sandbox(tmp_path)
    mirror = root / "website" / "plugins-index.json"
    document = json.loads(mirror.read_text(encoding="utf-8"))
    document["rows"][0]["summary"] = "hand-edited summary"
    mirror.write_text(json.dumps(document, sort_keys=True, separators=(",", ":")), encoding="utf-8")
    result = _run_tool("--check", root=root)
    assert result.returncode == 1, result.stdout + result.stderr
    assert "panel_drift:" in result.stderr


def test_write_then_check_round_trips(tmp_path: Path) -> None:
    """The sync path's write is idempotent: after --write, --check is green,
    and a second --write leaves the file byte-identical."""
    root = _sandbox(tmp_path)
    index = root / "website" / "index.html"
    first = _run_tool("--write", root=root)
    assert first.returncode == 0, first.stderr
    after_write = index.read_bytes()
    check = _run_tool("--check", root=root)
    assert check.returncode == 0, check.stderr
    second = _run_tool("--write", root=root)
    assert second.returncode == 0, second.stderr
    assert index.read_bytes() == after_write, "a second --write moved the bytes"
