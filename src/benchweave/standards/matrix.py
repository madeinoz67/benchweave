"""Compatibility matrix: deterministic render of manifest + SDK lock to markdown.

The committed ``docs/compatibility-matrix.md`` is generated, never hand
edited; :func:`check_matrix` is the staleness gate CI runs. Commit SHAs are
deliberately absent — they move per checkout — and stay in the ``versions``
output instead.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from typing import Any

from .check import LOCK_NAME
from .manifest import StandardEntry, load_manifest

DOCS_PATH = "docs/compatibility-matrix.md"
GENERATED_MARKER = "<!-- Generated by benchweave.standards matrix — do not edit manually. -->"
HEADER = (
    "| Standard | Schema/protocol version | Status | SDK version "
    "| Main-project range | Migration guidance | Sources |"
)
RULE = "| --- | --- | --- | --- | --- | --- | --- |"


def render_matrix(root: Path, sdk_root: Path | None = None) -> str:
    """Render the committed-artifact markdown from the manifest and lock."""
    sdk = sdk_root if sdk_root is not None else root / "packages" / "sdk"
    manifest = load_manifest(root)
    compatibility = _compatibility(_read_lock(sdk))
    sdk_version = str(compatibility.get("sdk") or "unknown")
    main_range = str(compatibility.get("main_project") or "unknown")
    notes = str(compatibility["notes"]) if compatibility.get("notes") else None
    sources = _sources(_origin_url(root), _origin_url(sdk))
    lines = [
        GENERATED_MARKER,
        "",
        "# Standards compatibility matrix",
        "",
        "Generated from `standards/standards-manifest.json` and the SDK",
        "`standards-lock.json`. One row per canonical standard; the standard",
        "version IS the schema/protocol version. Regenerate with",
        "`uv run python -m benchweave.standards matrix`; CI fails when the",
        "committed file is stale. Commit SHAs are not pinned here — run",
        "`uv run python -m benchweave.standards versions` for them.",
        "",
        HEADER,
        RULE,
    ]
    for entry in manifest.standards:
        lines.append(
            f"| {_cell(entry.id)} | {_cell(entry.version)} | {_cell(entry.status)} "
            f"| {_cell(sdk_version)} | {_cell(main_range)} "
            f"| {_cell(_guidance(entry, notes))} | {sources} |"
        )
    lines.append("")
    return "\n".join(lines)


def check_matrix(root: Path, sdk_root: Path | None = None) -> list[str]:
    """``[]`` when the committed matrix equals a fresh render; else one failure."""
    committed = root / DOCS_PATH
    if not committed.is_file():
        return [f"stale_matrix: {DOCS_PATH} absent; run python -m benchweave.standards matrix"]
    if committed.read_text(encoding="utf-8") != render_matrix(root, sdk_root):
        return [
            f"stale_matrix: {DOCS_PATH} differs from the rendered matrix; "
            "run python -m benchweave.standards matrix"
        ]
    return []


def _guidance(entry: StandardEntry, notes: str | None) -> str:
    if entry.status == "deprecated":
        if notes:
            return f"Deprecated — {notes}"
        return "Deprecated — migration guidance pending (compatibility.notes unfilled)"
    if entry.supersedes:
        return f"Supersedes {entry.supersedes}"
    return "—"


def _sources(main_url: str, sdk_url: str) -> str:
    main = f"[main repo]({main_url})" if main_url else "main repo"
    sdk = f"[sdk repo]({sdk_url})" if sdk_url else "sdk repo"
    return f"{main} · {sdk}"


def _origin_url(repo: Path) -> str:
    """Static origin URL of a checkout; empty when no origin is configured."""
    result = subprocess.run(
        ["git", "-C", str(repo), "config", "--get", "remote.origin.url"],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        return ""
    url = result.stdout.strip()
    if url.startswith("git@"):
        url = "https://" + url.removeprefix("git@").replace(":", "/", 1)
    return url.removesuffix(".git")


def _cell(value: str) -> str:
    return value.replace("|", "\\|")


def _compatibility(lock: dict[str, Any]) -> dict[str, Any]:
    block = lock.get("compatibility")
    return block if isinstance(block, dict) else {}


def _read_lock(sdk: Path) -> dict[str, Any]:
    path = sdk / LOCK_NAME
    if not path.is_file():
        return {"standards": []}
    lock: dict[str, Any] = json.loads(path.read_bytes())
    return lock
